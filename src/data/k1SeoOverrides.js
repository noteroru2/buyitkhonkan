const normalizePath = (pathname = '/') => {
  let decoded = pathname || '/';
  try {
    decoded = decodeURI(decoded);
  } catch {
    // Keep the original pathname if decoding fails.
  }
  if (!decoded.startsWith('/')) decoded = `/${decoded}`;
  if (decoded !== '/' && !decoded.endsWith('/')) decoded += '/';
  return decoded;
};

